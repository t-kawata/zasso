#!/usr/bin/env node
/**
 * generate-dir-template.js — Generate actual directories/files from Dirs-Tree.json
 *
 * --dirs-tree=<path> --root-dir=<path> --lang=<lang> [--dry-run] [--force] [--delete]
 *
 * Generates actual directories and template files based on Dirs-Tree.json.
 * Pass 1: Discover items to generate (no file creation)
 * Confirmation prompt: After confirmation (TTY only / skipped with --force)
 * Pass 2: Actual file creation
 *
 * Each file generation automatically applies the following:
 *   - Header comment: Metadata derived from the graph (source, mapped nodes, language, etc.)
 *     generated by boundify-helpers.js generateHeaderComment(), inserted at file top (PX-30)
 *   - Declaration stub: For empty files with no implementation, inserts a declaration stub
 *     based on kind and language (PX-28)
 *   - Cross-references: For files connected to prose-type nodes, embeds connection info
 *     inside the header comment (PX-30)
 *
 * Output contract:
 *   Success -> {"ok":true, "created":[...]} (exit code 0)
 *   Failure -> {"ok":false, "error":"..."} (exit code 1)
 */

'use strict';

const fs = require('fs');
const path = require('path');
const helpers = require('./boundify-helpers.js');

// ============================================================
// Constants
// ============================================================

/** List of supported languages */
const SUPPORTED_LANGUAGES = Object.freeze(['rust', 'go', 'typescript']);

/** Three-line template error -- missing arguments */
const ERROR_MISSING_ARGS = '[ERROR] Insufficient arguments\nCause: --dirs-tree=<path> --root-dir=<path> --lang=<lang> required\nAction: Re-run with all three arguments';

/** Three-line template error -- unsupported language */
const ERROR_UNSUPPORTED_LANG = (lang) =>
  `[ERROR] Unsupported language: ${lang}\nCause: specify one of rust/go/typescript\nAction: Specify a valid language`;

/** Three-line template error -- file not found */
const ERROR_FILE_NOT_FOUND = (filePath) =>
  `[ERROR] File not found: ${filePath}\nCause: File does not exist at the specified path\nAction: Specify a valid path`;

/** Three-line template error -- JSON parse failure */
const ERROR_PARSE_FAILED = (filePath, message) =>
  `[ERROR] JSON parse failed: ${filePath}\nCause: ${message}\nAction: Verify the file is valid JSON`;

/** Three-line template error -- language tree not found */
const ERROR_LANG_TREE_NOT_FOUND = (lang) =>
  `[ERROR] Tree for language ${lang} not found in Dirs-Tree.json\nCause: Tree definition for that language does not exist\nAction: Verify Dirs-Tree.json contains the correct language tree`;

/** Three-line template error -- file already exists */
const ERROR_FILE_EXISTS = (filePath) =>
  `[ERROR] File already exists: ${filePath}\nCause: A file with the same name already exists at the output location\nAction: Use --force to overwrite, or move the existing file`;

/** Three-line template error -- file deletion failed */
const ERROR_DELETE_FAILED = (filePath, message) =>
  `[ERROR] Deletion failed: ${filePath}\nCause: ${message}\nAction: Check permissions and file status`;
const ERROR_CREATE_FAILED = (filePath, message) =>
  `[ERROR] File creation failed: ${filePath}\nCause: ${message}\nAction: Check permissions and disk space`;

// ============================================================
// CLI argument parsing
// ============================================================

/**
 * Parse CLI arguments and return the result.
 *
 * @param {string[]} argv - Command-line argument array
 * @returns {object} Result. Success: {ok:true, dirsTreePath, rootDir, lang, isDryRun, isForce, isDelete}
 *                   Failure: {ok:false, error:string}
 */
function parseArgs(argv) {
  const dirsTreeFlag = argv.find(a => a.startsWith('--dirs-tree='));
  const rootDirFlag = argv.find(a => a.startsWith('--root-dir='));
  const langFlag = argv.find(a => a.startsWith('--lang='));
  const isDryRun = argv.includes('--dry-run');
  const isForce = argv.includes('--force');
  const isDelete = argv.includes('--delete');

  if (!dirsTreeFlag) {
    return { ok: false, error: ERROR_MISSING_ARGS };
  }
  if (!rootDirFlag) {
    return { ok: false, error: ERROR_MISSING_ARGS };
  }
  if (!langFlag) {
    return { ok: false, error: ERROR_MISSING_ARGS };
  }

  const lang = langFlag.slice('--lang='.length);
  if (!SUPPORTED_LANGUAGES.includes(lang)) {
    return { ok: false, error: ERROR_UNSUPPORTED_LANG(lang) };
  }

  return {
    ok: true,
    dirsTreePath: path.resolve(dirsTreeFlag.slice('--dirs-tree='.length)),
    rootDir: path.resolve(rootDirFlag.slice('--root-dir='.length)),
    lang,
    isDryRun,
    isForce,
    isDelete,
  };
}

// ============================================================
// Discovery — scan items to generate
// ============================================================

/**
 * Recursively traverse Dirs-Tree nodes and return a list of items to generate.
 *
 * @param {object} node - Tree node to traverse ({name, type, children?, declarationStub?})
 * @param {string} currentPath - Current parent directory path
 * @param {object} [headerContext] - Context for header comment generation (defaults to declaration stubs only when omitted)
 * @param {string} headerContext.graphDirAbs - Absolute directory path of the graph file
 * @param {string} headerContext.graphBasename - graph.basename
 * @param {string} headerContext.dirsTreeBasename - Base name of Dirs-Tree.json
 * @param {string} headerContext.sourceBasename - Base name of the source RFC
 * @param {Array} headerContext.crossReferences - Cross-reference array
 * @param {object} headerContext.nodeMetaMap - nodeId → {title, headingRef} map
 * @returns {Array<{type:string, path:string, size?:number, content?:string}>}
 *   Array of items to generate (no file creation)
 */
function discover(node, currentPath, headerContext) {
  const fullPath = path.join(currentPath, node.name);
  const created = [];

  if (node.type === 'directory') {
    created.push({ type: 'directory', path: fullPath });
    if (node.children) {
      for (const child of node.children) {
        const childItems = discover(child, fullPath, headerContext);
        created.push(...childItems);
      }
    }
  } else if (node.type === 'file') {
    let content = '';

    // PX-30: Prepend header comment (only when headerContext is provided)
    if (headerContext) {
      const headerPaths = helpers.resolveHeaderPaths(
        fullPath,
        headerContext.graphDirAbs,
        headerContext.graphBasename,
        headerContext.dirsTreeBasename,
        headerContext.sourceBasename
      );

      // Filter to prose nodes related to this file's mappedNodeIds
      const mappedNodeIdStrings = (node.mappedNodeIds || []).map(function (e) {
        return (typeof e === 'string') ? e : e.nodeId;
      });
      const mappedNodeIdsSet = new Set(mappedNodeIdStrings);
      const fileCrossRefs = (headerContext.crossReferences || []).filter(function (cr) {
        return cr.connections && cr.connections.some(function (conn) {
          return mappedNodeIdsSet.has(conn.toNodeId);
        });
      });

      const headerComment = helpers.generateHeaderComment(
        headerPaths,
        node.mappedNodeIds || [],
        mappedNodeIdStrings,
        fileCrossRefs,
        headerContext.graphBasename,
        headerContext.sourceBasename,
        headerContext.lang
      );
      content += headerComment + '\n';
    }

    // Append declaration stub if defined
    if (node.declarationStub) {
      content += node.declarationStub + '\n\n';
    }

    // Append stub markers at end of file (indicate node IDs and titles requiring implementation)
    const stubEntries = (node.mappedNodeIds || []).filter(function (e) {
      return typeof e !== 'string';
    });
    if (stubEntries.length > 0) {
      content += '\n';
      for (let si = 0; si < stubEntries.length; si++) {
        const entry = stubEntries[si];
        content += '// TODO: [::STUB::] MUST implement NODE_ID=' + entry.nodeId + ': ' + (entry.title || '') + '\n';
      }
    }
    created.push({ type: 'file', path: fullPath, size: content.length, content });
  }

  return created;
}

// ============================================================
// Generate dry-run output
// ============================================================

/**
 * Generate dry-run mode output JSON.
 *
 * @param {Array} created - Return value of discover()
 * @param {string} lang - Target language
 * @returns {object} dry-run output JSON
 */
function runDryRun(created, lang) {
  return {
    ok: true,
    dryRun: true,
    language: lang,
    created: created.map(c => ({ type: c.type, path: c.path })),
    total: created.length,
    note: 'dry-run mode. Remove --dry-run and re-run to actually generate.',
  };
}

// ============================================================
// readline confirmation prompt
// ============================================================

/**
 * Show a confirmation prompt to the user and return whether to continue.
 *
 * Prompts only on TTY. Always returns true on non-TTY or with --force.
 *
 * @param {Array} created - Return value of discover()
 * @param {boolean} isForce - --force flag
 * @returns {Promise<boolean>} true to continue
 */
async function confirmPrompt(created) {
  if (!process.stdin.isTTY) {
    return true;
  }

  const rl = require('readline').createInterface({ input: process.stdin, output: process.stderr });
  const summary = created
    .filter(c => c.type === 'file')
    .map(c => `  ${c.path}`)
    .join('\n');
  process.stderr.write(`The following ${created.length} items will be generated:\n${summary}\n\nContinue? (y/N): `);

  const answer = await new Promise(resolve => rl.question('', resolve));
  rl.close();
  return answer.toLowerCase() === 'y';
}

// ============================================================
// Pass 2 — actual file/directory creation
// ============================================================

/**
 * Create actual directories and files based on discovery results.
 *
 * @param {Array} created - Return value of discover()
 * @param {boolean} isForce - true to allow overwriting
 * @returns {Array<{type:string, path:string, action:string}>} Creation results
 * @throws {Error} If file exists and isForce is false
 */
function createItems(created, isForce) {
  const actuallyCreated = [];

  for (const item of created) {
    if (item.type === 'directory') {
      fs.mkdirSync(item.path, { recursive: true });
      actuallyCreated.push({ type: 'directory', path: item.path, action: 'created' });
    } else if (item.type === 'file') {
      if (fs.existsSync(item.path) && !isForce) {
        throw new Error(ERROR_FILE_EXISTS(item.path));
      }
      try {
        fs.writeFileSync(item.path, item.content, 'utf-8');
      } catch (err) {
        throw new Error(ERROR_CREATE_FAILED(item.path, err.message));
      }
      actuallyCreated.push({
        type: 'file',
        path: item.path,
        action: fs.existsSync(item.path) && isForce ? 'overwritten' : 'created',
      });
    }
  }

  return actuallyCreated;
}

// ============================================================
// Delete mode — fully remove generated files/directories
// ============================================================

/**
 * Delete generated files and directories based on discovery results.
 *
 * Deletes in reverse order (files first, then directories from leaves toward roots).
 * This prevents parent directories from becoming non-empty during deletion.
 * Skips items that do not exist (idempotent).
 *
 * @param {Array} created - Return value of discover()
 * @returns {Array<{type:string, path:string, action:string}>} Deletion results
 */
function deleteItems(created) {
  const results = [];

  // Process in reverse order (files first, then directories from leaves upward)
  const reversed = [...created].reverse();

  for (const item of reversed) {
    if (!fs.existsSync(item.path)) {
      results.push({ type: item.type, path: item.path, action: 'not_found' });
      continue;
    }

    try {
      if (item.type === 'file') {
        fs.unlinkSync(item.path);
        results.push({ type: 'file', path: item.path, action: 'deleted' });
      } else if (item.type === 'directory') {
        // Only delete empty directories (children should have been removed first)
        try {
          fs.rmdirSync(item.path);
          results.push({ type: 'directory', path: item.path, action: 'deleted' });
        } catch (dirErr) {
          if (dirErr.code === 'ENOTEMPTY' || dirErr.code === 'ENOTDIR') {
            results.push({ type: 'directory', path: item.path, action: 'skipped_not_empty' });
          } else {
            throw dirErr;
          }
        }
      }
    } catch (err) {
      throw new Error(ERROR_DELETE_FAILED(item.path, err.message));
    }
  }

  return results;
}

// ============================================================
// Build header comment context (buildHeaderContext)
// PX-30: Build context from Dirs-Tree.json to pass to discover
// ============================================================

/**
 * Build the context needed for header comment generation from Dirs-Tree.json.
 *
 * @param {object} dirsTree - Parsed result of Dirs-Tree.json
 * @param {string} dirsTreePath - Absolute path to Dirs-Tree.json
 * @param {string} rootDir - Absolute path to the generation root directory
 * @param {string} lang - Target language
 * @returns {object|null} Header context, or null if cannot be built
 */
function buildHeaderContext(dirsTree, dirsTreePath, rootDir, lang) {
  const sourceGraph = dirsTree.sourceGraph;
  const sourceFile = dirsTree.sourceFile;
  if (!sourceGraph) return null;

  const graphDirAbs = path.dirname(sourceGraph);
  const graphBasename = path.basename(sourceGraph);
  const sourceBasename = sourceFile ? path.basename(sourceFile) : 'UNKNOWN_SOURCE.md';
  const dirsTreeBasename = path.basename(dirsTreePath);

  // Build nodeMetaMap (node.title and node.headingRef from graph.sourceFile are
  // not stored directly in Dirs-Tree.json, so collect them from crossReferences)
  const nodeMetaMap = {};
  const crossReferences = (dirsTree.trees && dirsTree.trees[lang] && dirsTree.trees[lang].crossReferences) || [];
  for (let i = 0; i < crossReferences.length; i++) {
    const cr = crossReferences[i];
    nodeMetaMap[cr.nodeId] = { title: cr.title || '', headingRef: cr.headingRef || '' };
  }

  return {
    graphDirAbs: graphDirAbs,
    graphBasename: graphBasename,
    dirsTreeBasename: dirsTreeBasename,
    sourceBasename: sourceBasename,
    crossReferences: crossReferences,
    nodeMetaMap: nodeMetaMap,
    lang: lang,
  };
}

// ============================================================
// Main entry point
// ============================================================

/**
 * Main processing — parse args, discover, confirm, create, output JSON.
 *
 * @param {string[]} [testArgs] - Test argument array (defaults to process.argv.slice(2))
 */
async function main(testArgs) {
  const args = testArgs || process.argv.slice(2);

  const parsed = parseArgs(args);
  if (!parsed.ok) {
    console.error(parsed.error);
    process.exit(1);
    return;
  }

  const { dirsTreePath, rootDir, lang, isDryRun, isForce, isDelete } = parsed;

  let dirsTree;
  try {
    const raw = fs.readFileSync(dirsTreePath, 'utf-8');
    dirsTree = JSON.parse(raw);
  } catch (err) {
    if (err.code === 'ENOENT') {
      console.error(ERROR_FILE_NOT_FOUND(dirsTreePath));
    } else {
      console.error(ERROR_PARSE_FAILED(dirsTreePath, err.message));
    }
    process.exit(1);
    return;
  }

  const tree = dirsTree.trees && dirsTree.trees[lang];
  if (!tree) {
    const msg = `${lang} has no definition in Dirs-Tree.json, exiting normally without creating anything.`;
    console.log(msg);
    process.exit(0);
    return;
  }

  // PX-30: Build header comment generation context
  const headerContext = buildHeaderContext(dirsTree, dirsTreePath, rootDir, lang);

  // Pass 1: Discover items to generate
  const created = discover(tree, rootDir, headerContext);

  // --delete mode: Fully remove generated items
  if (isDelete) {
    // dry-run mode: Show deletion plan and exit
    if (isDryRun) {
      process.stdout.write(JSON.stringify({
        ok: true,
        dryRun: true,
        deleteMode: true,
        language: lang,
        toBeDeleted: created.map(c => ({ type: c.type, path: c.path })),
        total: created.length,
        note: 'dry-run mode. Remove --dry-run from --delete and re-run to actually delete.',
      }) + '\n');
      return;
    }

    try {
      const deleteResults = deleteItems(created);
      process.stdout.write(JSON.stringify({
        ok: true,
        dryRun: false,
        deleteMode: true,
        language: lang,
        deleted: deleteResults,
        total: deleteResults.length,
      }) + '\n');
    } catch (err) {
      console.error(err.message);
      process.exit(1);
    }
    return;
  }

  // dry-run mode (creation): Show plan and exit
  if (isDryRun) {
    process.stdout.write(JSON.stringify(runDryRun(created, lang)) + '\n');
    return;
  }

  // Confirmation prompt (skipped with --force)
  if (!isForce) {
    const confirmed = await confirmPrompt(created);
    if (!confirmed) {
      process.stdout.write(JSON.stringify({
        ok: false,
        cancelled: true,
        message: 'Cancelled by user',
      }) + '\n');
      return;
    }
  }

  // Pass 2: Create actual files
  try {
    const actuallyCreated = createItems(created, isForce);
    process.stdout.write(JSON.stringify({
      ok: true,
      dryRun: false,
      language: lang,
      created: actuallyCreated,
      total: actuallyCreated.length,
    }) + '\n');
  } catch (err) {
    console.error(err.message);
    process.exit(1);
    return;
  }
}

// ============================================================
// Entry point (CLI execution)
// ============================================================

if (require.main === module) {
  main().catch(e => {
    console.error(`[ERROR] ${e.message}`);
    process.exit(1);
  });
}

module.exports = { parseArgs, discover, runDryRun, confirmPrompt, createItems, buildHeaderContext, main };
