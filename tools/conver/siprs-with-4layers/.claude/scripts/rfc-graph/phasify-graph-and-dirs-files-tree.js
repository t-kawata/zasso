#!/usr/bin/env node

/**
 * phasify-graph-and-dirs-files-tree.js — Graph node phase grouping (foundation skeleton)
 *
 * Used in split-to-tickets.md Step 4. Takes GRAPH.json and Dirs-Tree.json as input,
 * groups graph nodes into implementation phases, and writes to Tickets.json.
 *
 * The core algorithms (SCC condensation, weighted topological sort, phase merging) are
 * implemented as Phase 1-5 of this script (handled by PX-38).
 *
 * This file (PX-37) provides the following foundation:
 * - Argument parsing (--dry-run, --verbose)
 * - Dirs-Tree.json existence check
 * - Tickets.json existence check and creation
 * - Invocation of the validation sub-script (validate-phasify.js)
 *
 * Usage:
 *   node phasify-graph-and-dirs-files-tree.js <GRAPH.json> <Dirs-Tree.json> [--dry-run] [--verbose]
 *
 * Arguments:
 *   GRAPH.json      — Graph JSON generated by graphify-rfc (required)
 *   Dirs-Tree.json  — Directory tree JSON generated by boundify-graph (required)
 *   --dry-run       — Suppress writing to Tickets.json, stdout only
 *   --verbose       — Display detailed processing progress to stdout
 *
 * Exit codes:
 *   0 = Success
 *   1 = Validation error
 *   2 = Argument error
 *   3 = File not found
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { toHomeRelative } = require('../lib/path-utils');

// ============================================================
// Constants
// ============================================================

/** Minimum nodes per phase */
const MIN_NODES_PER_PHASE = 10;

/** Path to the ticket skeleton generation script (relative to this script) */
const WRITE_TICKETS_TEMPLATE_PATH = '../tickets/write-tickets-json-template.js';

// PX-38 import: Core algorithm pure function group
const {
  getWeight,
  isHard,
  kahnTopologicalSort,
  computeSoftViolations,
  mergePhases,
  enforceHardConstraints,
  consolidatePhases,
  reassignPhaseIds,
  buildSccConstraint,
  applySccToOrder,
  applyDirectoryConstraints,
  phasesToTicketsFormat,
} = require('./phasify-helpers.js');

// PX-38 import: SCC condensation (reused from boundify-helpers.js)
const { tarjanSCC } = require('./boundify-helpers.js');

// PX-38 import: node→dir map (reused from validate-phasify.js)
const { buildNodeToDirMap } = require('./validate-phasify.js');

// PX-38 import: Validation sub-script (enables in-memory validation even during dry-run)
const { validateAll } = require('./validate-phasify.js');

// ============================================================
// Struct: CliOptions
// ============================================================

/**
 * @typedef {object} CliOptions
 * @property {string} graphPath     — Absolute path to GRAPH.json
 * @property {string} dirsTreePath  — Absolute path to Dirs-Tree.json
 * @property {string} ticketsPath   — Absolute path to Tickets.json (auto-derived)
 * @property {boolean} dryRun      — --dry-run flag
 * @property {boolean} verbose     — --verbose flag
 */

// ============================================================
// Functions
// ============================================================

/**
 * Parse CLI arguments and return CliOptions.
 * On error, displays an error message and calls process.exit(2).
 *
 * @param {string[]} argv — Equivalent to process.argv.slice(2)
 * @returns {CliOptions}
 */
function parseArguments(argv) {
  const positionalArgs = [];
  const flags = {};

  for (const arg of argv) {
    if (arg.startsWith('--')) {
      const flagName = arg.slice(2);
      if (flagName === 'dry-run' || flagName === 'verbose') {
        flags[flagName] = true;
      } else {
        console.error('[ERROR] Unknown flag: ' + arg);
        console.error('Usage: node phasify-graph-and-dirs-files-tree.js <GRAPH.json> <Dirs-Tree.json> [--dry-run] [--verbose]');
        process.exit(2);
      }
    } else {
      positionalArgs.push(arg);
    }
  }

  if (positionalArgs.length < 2) {
    console.error('[ERROR] Insufficient arguments. Both GRAPH.json and Dirs-Tree.json are required.');
    console.error('Usage: node phasify-graph-and-dirs-files-tree.js <GRAPH.json> <Dirs-Tree.json> [--dry-run] [--verbose]');
    process.exit(2);
  }

  const graphPath = path.resolve(positionalArgs[0]);
  const dirsTreePath = path.resolve(positionalArgs[1]);

  return {
    graphPath,
    dirsTreePath,
    ticketsPath: '',
    dryRun: !!flags['dry-run'],
    verbose: !!flags['verbose'],
  };
}

/**
 * Derive the Tickets.json path from two file paths.
 * Requires both paths to have the same dirname.
 *
 * @param {string} graphPath — Absolute path to GRAPH.json
 * @param {string} dirsTreePath — Absolute path to Dirs-Tree.json
 * @returns {string} Absolute path to Tickets.json
 */
function resolveTicketsPath(graphPath, dirsTreePath) {
  const graphDir = path.dirname(graphPath);
  const dirsTreeDir = path.dirname(dirsTreePath);
  if (graphDir !== dirsTreeDir) {
    console.error('[ERROR] GRAPH.json and Dirs-Tree.json must be in the same directory.');
    console.error('  GRAPH.json directory: ' + graphDir);
    console.error('  Dirs-Tree.json directory: ' + dirsTreeDir);
    process.exit(2);
  }
  return path.join(graphDir, 'Tickets.json');
}

/**
 * Check that Dirs-Tree.json exists. Exits with error if not found.
 *
 * @param {string} dirsTreePath — Absolute path to Dirs-Tree.json
 */
function checkDirsTreeExists(dirsTreePath) {
  if (!fs.existsSync(dirsTreePath)) {
    console.error('[ERROR] Dirs-Tree.json not found: ' + dirsTreePath);
    console.error('Run boundify-graph first.');
    console.error('  Example: /boundify-graph ' + dirsTreePath.replace(/-Dirs-Tree\.json$/, '') + '-GRAPH.json');
    process.exit(3);
  }
}

/**
 * Check that Tickets.json exists; create a new one if it doesn't.
 *
 * @param {string} ticketsPath — Absolute path to Tickets.json
 * @param {string} graphPath — Absolute path to GRAPH.json
 * @param {string} dirsTreePath — Absolute path to Dirs-Tree.json
 * @param {boolean} dryRun — If true, skip actual writing
 * @returns {boolean} true if newly created, false if already existed
 */
function ensureTicketsJsonExists(ticketsPath, graphPath, dirsTreePath, dryRun) {
  if (fs.existsSync(ticketsPath)) {
    return false;
  }

  if (dryRun) {
    console.log('[INFO] --dry-run mode: Tickets.json does not exist, skipping generation.');
    return true;
  }

  // Call write-tickets-json-template.js to generate a skeleton
  const templateScript = path.resolve(__dirname, WRITE_TICKETS_TEMPLATE_PATH);
  if (!fs.existsSync(templateScript)) {
    console.error('[ERROR] write-tickets-json-template.js not found: ' + templateScript);
    process.exit(3);
  }

  // rfcPath is mechanically derived from graphPath (e.g., RFC-ROOT-GRAPH.json → -GRAPH.json → .md)
  const rfcPath = graphPath.endsWith('-GRAPH.json')
    ? graphPath.slice(0, -11) + '.md'
    : graphPath.replace(/\.json$/, '.md');

  const metadata = JSON.stringify({
    title: 'phasify auto-generated ticket decomposition design document',
    source: toHomeRelative(rfcPath),
    generatedAt: new Date().toISOString().split('T')[0],
    analyzedSections: 'Auto-generated by phasify-graph-and-dirs-files-tree.js',
    resolvedPaths: {
      rfcPath: toHomeRelative(rfcPath),
      graphPath: toHomeRelative(graphPath),
      dirsTreePath: toHomeRelative(dirsTreePath),
    },
  });

  const { spawnSync } = require('child_process');
  const result = spawnSync('node', [templateScript, ticketsPath, metadata], {
    stdio: ['inherit', 'pipe', 'pipe'],
    encoding: 'utf8',
  });

  if (result.status !== 0) {
    console.error('[ERROR] Tickets.json skeleton generation failed.');
    console.error(result.stderr || result.stdout);
    process.exit(1);
  }

  return true;
}

/**
 * Output verbose log (only when --verbose is set).
 *
 * @param {string} message
 * @param {boolean} verbose
 */
function logVerbose(message, verbose) {
  if (verbose) {
    console.log('[VERBOSE] ' + message);
  }
}

// ============================================================
// Main entry point (skeleton)
// ============================================================

/**
 * Main processing.
 * Phase 1-5 (SCC condensation, topological sort, phase merging) are
 * added to this function by PX-38.
 *
 * @param {CliOptions} opts
 */
// [::TICKET::] PX-114 changes. Details: `node .claude/scripts/tickets/show-ticket-context.js --ticket-key=PX-114 --for-spec --no-implementation-order`.
function runPhasify(opts) {
  logVerbose('Loading GRAPH.json...', opts.verbose);
  const graphData = JSON.parse(fs.readFileSync(opts.graphPath, 'utf8'));
  const nodes = graphData.nodes || [];
  const edges = graphData.edges || [];
  logVerbose('Nodes: ' + nodes.length + ', Edges: ' + edges.length, opts.verbose);

  logVerbose('Loading Dirs-Tree.json...', opts.verbose);
  const dirsTreeData = JSON.parse(fs.readFileSync(opts.dirsTreePath, 'utf8'));

  // ============================================================
  // Phase 1: SCC condensation (tarjanSCC)
  // ============================================================
  logVerbose('Phase 1: Running SCC condensation...', opts.verbose);
  const sccResult = tarjanSCC(edges);
  const { sccMap, sccIds } = buildSccConstraint(sccResult);
  logVerbose('SCC detected: ' + sccResult.length + ' components (multi-node SCC: ' + Object.keys(sccMap).length + ' nodes)', opts.verbose);

  // ============================================================
  // Phase 2: Kahn topological sort + directory constraints
  // ============================================================
  logVerbose('Phase 2: Running topological sort...', opts.verbose);
  const allNodeIds = nodes.map(n => n.id);
  const sortResult = kahnTopologicalSort(allNodeIds, edges, getWeight);

  if (!sortResult.success) {
    console.error('[ERROR] ' + sortResult.error);
    console.error('Resolve circular dependencies and re-run.');
    process.exit(1);
  }

  // Apply SCC constraint to ordering (adjacent same-SCC nodes)
  const sccAppliedOrder = applySccToOrder(sortResult.order, sccMap);

  // Get directory constraints
  const nodeToDirMap = buildNodeToDirMap(dirsTreeData);
  const depDirs = dirsTreeData.dependencyDirections ? (dirsTreeData.dependencyDirections.rust || []) : [];

  // Apply directory constraints to ordering (all nodes in fromDir come before all nodes in toDir)
  let finalOrder = sccAppliedOrder;
  if (depDirs.length > 0) {
    logVerbose('Directory dependency directions: ' + depDirs.length + ' applied', opts.verbose);
    finalOrder = applyDirectoryConstraints(finalOrder, depDirs, nodeToDirMap);
  }

  logVerbose('Sort completed: ' + finalOrder.length + ' nodes', opts.verbose);

  // ============================================================
  // Phase 3: Soft constraint violation cost calculation
  // ============================================================
  logVerbose('Phase 3: Computing soft constraint violation costs...', opts.verbose);
  const softResult = computeSoftViolations(finalOrder, edges, getWeight);
  if (softResult.violations.length > 0 && opts.verbose) {
    console.log('[VERBOSE] Soft constraint violations: ' + softResult.violations.length + ', total cost: ' + softResult.totalCost);
    for (const violation of softResult.violations) {
      console.log('  ' + violation.from + ' → ' + violation.to + ' (' + violation.type + ', cost=' + violation.cost + ')');
    }
  } else if (opts.verbose) {
    console.log('[VERBOSE] Soft constraint violations: none');
  }

  // ============================================================
  // Phase 4: Phase merging and discretization (minimum 10 nodes)
  // ============================================================
  logVerbose('Phase 4: Running phase merging (minimum: ' + MIN_NODES_PER_PHASE + ' nodes)...', opts.verbose);
  // Extract hard constraint edges (depends_on/implements/constrains)
  const hardEdges = edges.filter(function(e) { return isHard(e.type); });
  let phaseAssignments = mergePhases(finalOrder, MIN_NODES_PER_PHASE, hardEdges);

  // Post-adjustment: ensure both endpoints of depends_on are not in the same phase
  if (hardEdges.length > 0) {
    const beforeCount = phaseAssignments.length;
    phaseAssignments = enforceHardConstraints(phaseAssignments, hardEdges);
    const midCount = phaseAssignments.length;
    // Consolidate phases that became too small after splitting
    phaseAssignments = consolidatePhases(phaseAssignments, hardEdges, MIN_NODES_PER_PHASE);
    const afterCount = phaseAssignments.length;
    if (opts.verbose && (midCount !== beforeCount || afterCount !== midCount)) {
      logVerbose('Hard constraint adjustment: ' + beforeCount + ' → ' + midCount + ' → ' + afterCount + ' phases', opts.verbose);
    }
  }

  // Reassign phase IDs in array order (= implementation order)
  phaseAssignments = reassignPhaseIds(phaseAssignments);

  logVerbose('Phase count: ' + phaseAssignments.length, opts.verbose);

  // Warn if any phase has fewer than 10 nodes
  for (const phase of phaseAssignments) {
    const size = phase.nodeIds ? phase.nodeIds.length : 0;
    if (size < MIN_NODES_PER_PHASE && nodes.length >= MIN_NODES_PER_PHASE) {
      console.warn('[WARN] Phase P' + phase.id + ' has ' + size + ' nodes (below minimum ' + MIN_NODES_PER_PHASE + ')');
    }
  }

  // ============================================================
  // Phase 5: Build phase info in Tickets.json format in memory
  // ============================================================
  logVerbose('Phase 5: Converting phase info to Tickets.json format...', opts.verbose);
  const ticketsPhases = phasesToTicketsFormat(phaseAssignments);

  // Build in-memory Tickets.json data (for validation and writing)
  const rfcPath = opts.graphPath.endsWith('-GRAPH.json')
    ? opts.graphPath.slice(0, -11) + '.md'
    : opts.graphPath.replace(/\.json$/, '.md');
  const inMemoryTickets = {
    title: 'phasify auto-generated',
    round: 1,
    metadata: {
      source: toHomeRelative(rfcPath),
      generatedAt: new Date().toISOString().split('T')[0],
      analyzedSections: 'Auto-generated by phasify-graph-and-dirs-files-tree.js',
      resolvedPaths: {
        rfcPath: toHomeRelative(rfcPath),
        graphPath: toHomeRelative(opts.graphPath),
        dirsTreePath: toHomeRelative(opts.dirsTreePath),
      },
    },
    phases: ticketsPhases,
  };

  // ============================================================
  // User-facing report output (always stdout)
  // ============================================================
  console.log('');
  console.log('=== phasify Phase Design Report ===');
  console.log('Input graph: ' + opts.graphPath);
  console.log('Input Dirs-Tree: ' + opts.dirsTreePath);
  console.log('Output Tickets.json: ' + opts.ticketsPath);
  console.log('Total nodes: ' + nodes.length);
  console.log('Total edges: ' + edges.length);
  console.log('Total phases: ' + phaseAssignments.length);
  console.log('====================================');

  // ============================================================
  // Validation (validate in-memory data directly — accurate even with --dry-run)
  // ============================================================
  logVerbose('Running validation...', opts.verbose);
  const validateResult = validateAll(inMemoryTickets, nodes, edges, dirsTreeData);

  // Summary line always shown (not verbose-only)
  const hardViolations = validateResult.checks.hardConstraints ?
    validateResult.checks.hardConstraints.violations.length : 0;
  const sizeIssues = validateResult.checks.phaseSizeMinimum ?
    validateResult.checks.phaseSizeMinimum.issues.filter(function(i) { return !i.isWarning; }).length : 0;
  const allCovered = validateResult.checks.allNodesCovered ?
    validateResult.checks.allNodesCovered.passed : false;
  const noOrphans = validateResult.checks.noOrphanNodes ?
    validateResult.checks.noOrphanNodes.passed : false;
  const dirsOk = validateResult.checks.dirsConstraint ?
    validateResult.checks.dirsConstraint.passed : false;
  console.log((validateResult.valid ? '✅ PASS' : '⚠️ FAIL') + '\n\n' + phaseAssignments.length + ' phases, ' +
    (allCovered ? 'all ' + nodes.length + ' nodes covered' : 'uncovered nodes exist') + ', ' +
    'hard constraint violations: ' + hardViolations + ', ' +
    'phases below minimum 10: ' + sizeIssues +
    (sizeIssues > 0 ? ' (merging would violate dependency constraints, so this is the safe decision)' : ''));

  if (validateResult.valid) {
    console.log('Wrote ' + phaseAssignments.length + ' phases to ' + opts.ticketsPath + '.');
  } else {
    console.log('Validation results:');
    // console.log(JSON.stringify(validateResult, null, 2));
    console.log('[WARN] Validation failed but continuing due to --dry-run.');
  }

  // ============================================================
  // Write to Tickets.json (unless --dry-run)
  // ============================================================
  if (opts.dryRun) {
    console.log('');
    console.log('[--dry-run mode] Did not write to Tickets.json.');
    return;
  }

  // Read existing Tickets.json and replace phases
  const existingTickets = JSON.parse(fs.readFileSync(opts.ticketsPath, 'utf8'));
  existingTickets.phases = ticketsPhases;

  // Write
  fs.writeFileSync(opts.ticketsPath, JSON.stringify(existingTickets, null, 2) + '\n', 'utf8');
  logVerbose('Tickets.json updated: ' + opts.ticketsPath, opts.verbose);
}

/**
 * Entry point.
 */
function main() {
  const opts = parseArguments(process.argv.slice(2));
  opts.ticketsPath = resolveTicketsPath(opts.graphPath, opts.dirsTreePath);

  checkDirsTreeExists(opts.dirsTreePath);
  const created = ensureTicketsJsonExists(opts.ticketsPath, opts.graphPath, opts.dirsTreePath, opts.dryRun);
  if (created && !opts.dryRun) {
    console.log('[INFO] Tickets.json created: ' + opts.ticketsPath);
  }

  runPhasify(opts);
}

if (require.main === module) {
  main();
}

module.exports = {
  parseArguments,
  resolveTicketsPath,
  checkDirsTreeExists,
  ensureTicketsJsonExists,
  logVerbose,
  runPhasify,
  MIN_NODES_PER_PHASE,
};
